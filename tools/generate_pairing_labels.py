#!/usr/bin/env python3
"""Bake fixed system-screen text into 1-bit glyphs; no font file is embedded.

Requires Pillow and a locally licensed CJK font. Example on macOS:
  python3 tools/generate_pairing_labels.py '/System/Library/Fonts/STHeiti Medium.ttc'
The generated labels are UI assets, not request-controlled text. Dynamic client
names use the bounded ASCII font in pairing_screen.c.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
LABELS = [
 ('pair_title','连接相框',42),('compare','请核对两边的配对码',24),
 ('confirm','按功能键确认配对',28),('reset','功能键长按 8 秒重置配对',20),
 ('bound_title','配对完成',42),('bound_detail','可以发送图片了',26),
 ('ready_title','等待连接',42),('ready_detail','在网页中选择这台相框',26),
 ('cancel_title','配对已取消',42),('retry','请在网页中重新发起配对',24),
 ('expired_title','配对已过期',42),('error_title','配对未完成',42),
 ('error_detail','请重试或长按功能键重置',24),
]
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('font',type=Path)
 args=parser.parse_args();lines=['/* Generated by tools/generate_pairing_labels.py; 1-bit fixed UI labels. */','#pragma once','#include <stdint.h>','typedef struct {unsigned width,height;const uint8_t *bits;} pp_label;']
 for name,text,size in LABELS:
  font=ImageFont.truetype(str(args.font),size)
  box=font.getbbox(text);width,height=box[2]-box[0]+2,box[3]-box[1]+2
  image=Image.new('L',(width,height),255);ImageDraw.Draw(image).text((1-box[0],1-box[1]),text,font=font,fill=0)
  bits=bytearray((width*height+7)//8)
  for y in range(height):
   for x in range(width):
    if image.getpixel((x,y))<128: bits[(y*width+x)//8]|=1<<(7-(y*width+x)%8)
  lines.append('static const uint8_t label_'+name+'_bits[]={'+','.join('0x%02x'%b for b in bits)+'};')
  lines.append('static const pp_label label_'+name+'={%d,%d,label_%s_bits};'%(width,height,name))
 (Path(__file__).resolve().parents[1]/'main/pairing_labels.h').write_text('\n'.join(lines)+'\n')
if __name__=='__main__': main()
